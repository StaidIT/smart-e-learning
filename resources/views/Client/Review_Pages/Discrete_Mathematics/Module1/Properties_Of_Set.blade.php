<div class="mt-10" id="topic-properties-of-set">

    <h2 class="text-2xl font-bold">
        3. Properties of Set
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-4 leading-relaxed">
        Properties of sets are mathematical rules that describe how
        sets behave when different set operations are performed.
    </p>


    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-5">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Commutative Property
            </h4>

            <p class="text-gray-400 mt-2">
                The order of the sets does not affect the result.
            </p>

            <p class="text-white mt-3">
                A ∪ B = B ∪ A
            </p>

            <p class="text-white mt-1">
                A ∩ B = B ∩ A
            </p>

        </div>


        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Associative Property
            </h4>

            <p class="text-gray-400 mt-2">
                The grouping of sets does not affect the result.
            </p>

            <p class="text-white mt-3">
                (A ∪ B) ∪ C = A ∪ (B ∪ C)
            </p>

            <p class="text-white mt-1">
                (A ∩ B) ∩ C = A ∩ (B ∩ C)
            </p>

        </div>


        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Distributive Property
            </h4>

            <p class="text-gray-400 mt-2">
                Union and intersection can be distributed over each other.
            </p>

            <p class="text-white mt-3">
                A ∪ (B ∩ C) = (A ∪ B) ∩ (A ∪ C)
            </p>

            <p class="text-white mt-1">
                A ∩ (B ∪ C) = (A ∩ B) ∪ (A ∩ C)
            </p>

        </div>


        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Identity Property
            </h4>

            <p class="text-gray-400 mt-2">
                Combining a set with the empty or universal set follows
                specific rules.
            </p>

            <p class="text-white mt-3">
                A ∪ ∅ = A
            </p>

            <p class="text-white mt-1">
                A ∩ U = A
            </p>

        </div>


        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Complement Property
            </h4>

            <p class="text-gray-400 mt-2">
                A set and its complement have no elements in common.
            </p>

            <p class="text-white mt-3">
                A ∩ A′ = ∅
            </p>

            <p class="text-white mt-1">
                A ∪ A′ = U
            </p>

        </div>


        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">

            <h4 class="font-bold text-lg">
                Idempotent Property
            </h4>

            <p class="text-gray-400 mt-2">
                Combining a set with itself produces the same set.
            </p>

            <p class="text-white mt-3">
                A ∪ A = A
            </p>

            <p class="text-white mt-1">
                A ∩ A = A
            </p>

        </div>

    </div>

</div>